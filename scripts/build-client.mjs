#!/usr/bin/env node
// scripts/build-client.mjs — build lib/client.js from the client src files.
//
// Assembly (byte-exact against the pre-rename committed bundle, verified
// 2026-10-18 for INC-2026-10-18): banner + ModuleLoader prologue (the
// registration id is read from package.json "name" — the DSH web loader keys
// browser boot rows by npm package name, so the two must be identical), then
// src/client-core.js + one blank line + src/client-view.js with top-level
// `export ` prefixes stripped (both files must otherwise stay
// import/export-free plain JS), then the epilogue wiring
// createClientPluginBody(react).
//
// Provenance: the original generator was never committed in the fork baseline
// (6f068b2 shipped only the prebuilt lib/client.js). This file is the
// reconstructed, byte-faithful replacement: regenerating with the pre-rename
// name reproduces the committed bundle byte-for-byte.
//
// stateRoutePath deliberately stays on the server-side plugin id
// (dsh.plugin.json id = "dsh-schedule-later", stable across renames — see
// src/host-routes.js STATE_PATH and knowledge SYSTEM-029).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

// Registration id MUST equal the npm package name (loader row key).
const regId = pkg.name;

// Keep in sync with src/host-routes.js STATE_PATH.
const stateRoutePath = '/plugin-data/dsh-schedule-later/state';

const stripExport = (src) =>
  src
    .replace(/\n$/, '')
    .split('\n')
    .map((line) => (line.startsWith('export ') ? line.slice('export '.length) : line))
    .join('\n');

const core = stripExport(readFileSync(join(root, 'src', 'client-core.js'), 'utf8'));
const view = stripExport(readFileSync(join(root, 'src', 'client-view.js'), 'utf8'));

const lines = [
  '// GENERATED by scripts/build-client.mjs — do not edit by hand.',
  'window.__ModuleLoader__.load({',
  `\tid: "${regId}",`,
  '\tfactory: (require) => {',
  '\t\tvar module = { exports: {} };',
  '\t\tvar exports = module.exports;',
  '\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
  '\t\tvar react = require("react");',
  '\t\tvar react_jsx_runtime = react;',
  core,
  '',
  view,
  '',
  '\t\tvar built = createClientPluginBody(react)(/* config */ {',
  `\t\t\tstateRoutePath: "${stateRoutePath}",`,
  '\t\t});',
  '\t\texports.core = built.core;',
  '\t\texports.apply = built.apply;',
  '\t\texports.inject = built.inject;',
  '\t\treturn module.exports;',
  '\t}',
  '});',
];

writeFileSync(join(root, 'lib', 'client.js'), lines.join('\n') + '\n', 'utf8');
console.log(`lib/client.js: ${lines.length} lines, registration id "${regId}", stateRoutePath "${stateRoutePath}"`);
